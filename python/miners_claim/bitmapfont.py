def glyph(char: str) -> tuple[str, ...]:
    """Map lower case to capital glyphs, with visible replacement for unknowns."""
    return FONT.get(char.upper(), FONT['?'])


class PixelFont:
    """Minimal pygame-font-compatible adapter for .render and .size."""
    def __init__(self, scale: int = 1):
        if scale < 1:
            raise ValueError('Font scale must be positive')
        self.scale = scale
        self._cache: dict[tuple[str, tuple[int, ...]], object] = {}

    def size(self, message: str) -> tuple[int, int]:
        return (len(str(message)) * 6 * self.scale, 8 * self.scale)

    def render(self, message: str, antialias: bool, color):
        import pygame
        text = str(message)
        rgb = tuple(color)
        key = (text, rgb)
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        width, height = self.size(text)
        surface = pygame.Surface((max(1, width), height), pygame.SRCALPHA)
        for i, char in enumerate(text):
            for y, row in enumerate(glyph(char)):
                for x, pixel in enumerate(row):
                    if pixel == '1':
                        pygame.draw.rect(surface, rgb,
                                         ((i*6+x)*self.scale, y*self.scale,
                                          self.scale, self.scale))
        if len(self._cache) >= 256:
            self._cache.clear()
        self._cache[key] = surface
        return surface